#!/usr/bin/env node
// Generates js/config.js from .env (or real environment variables).
// Usage: node scripts/build-config.mjs        (or: npm run config)

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { ROOT, loadEnv } from './env.mjs';

// Decode a JWT payload without verifying it, to catch pasted secret keys.
function jwtRole(token) {
  const parts = String(token).split('.');
  if (parts.length !== 3) return null;
  try {
    return JSON.parse(Buffer.from(parts[1].replace(/-/g, '+').replace(/_/g, '/'), 'base64').toString('utf8')).role || null;
  } catch {
    return null;
  }
}

function isHttpUrl(v) {
  try {
    const u = new URL(v);
    return u.protocol === 'https:' || (u.protocol === 'http:' && /^(localhost|127\.0\.0\.1|0\.0\.0\.0|\[::1\])$/.test(u.hostname));
  } catch {
    return false;
  }
}

export function buildConfig(env) {
  const get = (k) => String(env[k] ?? '').trim();
  const errors = [];
  const warnings = [];

  const config = {
    appName: get('REFUTE_APP_NAME') || 'Refute',
    sourceUrl: get('REFUTE_SOURCE_URL'),
    supabaseUrl: get('SUPABASE_URL').replace(/\/+$/, ''),
    supabaseKey: get('SUPABASE_PUBLISHABLE_KEY') || get('SUPABASE_ANON_KEY'),
  };

  if (!config.supabaseUrl || !config.supabaseKey) {
    warnings.push('SUPABASE_URL or SUPABASE_PUBLISHABLE_KEY is empty. The site will show a setup page until both are set.');
  }
  if (config.supabaseUrl && !isHttpUrl(config.supabaseUrl)) {
    errors.push(`SUPABASE_URL must be an https:// address (or http://localhost for local Supabase). Got: ${config.supabaseUrl}`);
  }
  if (/^sb_secret_/.test(config.supabaseKey) || jwtRole(config.supabaseKey) === 'service_role') {
    errors.push('That is a SECRET Supabase key. It would give anyone full access to your database. Use the publishable key (sb_publishable_...) or the legacy anon key instead.');
  }
  if (config.sourceUrl && !isHttpUrl(config.sourceUrl)) errors.push('REFUTE_SOURCE_URL must start with https://');
  return { config, errors, warnings };
}

export function renderConfig(config) {
  return `// Generated by scripts/build-config.mjs from your .env file. Do not edit by hand:
// change .env and run \`npm run config\` again. This file is public, so it must
// never contain secret keys.
export const CONFIG = ${JSON.stringify(config, null, 2)};
`;
}

export function writeConfig({ root = ROOT, env = loadEnv(root), quiet = false } = {}) {
  const { config, errors, warnings } = buildConfig(env);
  for (const w of warnings) if (!quiet) console.warn(`warning: ${w}`);
  if (errors.length) {
    for (const e of errors) console.error(`error: ${e}`);
    return { ok: false, config };
  }
  writeFileSync(join(root, 'js', 'config.js'), renderConfig(config));
  if (!quiet) console.log(`Wrote js/config.js for ${config.appName}.`);
  return { ok: true, config };
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const { ok } = writeConfig();
  process.exit(ok ? 0 : 1);
}
